<?php

namespace App\Actions;

use App\Models\Device;
use App\Models\Plugin;
use App\Plugins\Enums\PluginOutput;
use App\Services\ImageGenerationService;
use Exception;
use Illuminate\Support\Facades\Log;

/**
 * Render a plugin into its own image cache (current_image) for a device, without
 * touching the device's current_screen_image. Re-renders only when the data is
 * stale or nothing is cached, unless forced.
 */
class RenderPluginImage
{
    /**
     * @param  bool  $force  Re-fetch data and re-render even when a fresh image is cached.
     * @param  string|null  $existingImageId  Image id to reuse when the generated bytes match the stored file.
     * @return string|null The cached image UUID, or null when the plugin opted out of display.
     *
     * @throws Exception when rendering fails
     */
    public function handle(Plugin $plugin, Device $device, bool $force = false, ?string $existingImageId = null): ?string
    {
        ImageGenerationService::resetIfNotCacheable($plugin, $device);
        $plugin->refresh();

        $isDataStale = $plugin->isDataStale();

        if ($force || $isDataStale) {
            $plugin->updateDataPayload();
            $plugin->refresh();
        }

        if ($this->shouldSkipFromPayload($plugin)) {
            Log::info('Skipping rendering because payload sets TRMNL_SKIP_DISPLAY', [
                'device_id' => $device->id,
                'plugin_id' => $plugin->id,
            ]);

            return null;
        }

        $output = $plugin->handler()?->output();

        if ($output === PluginOutput::ProcessedImage) {
            return $plugin->current_image;
        }

        if (! $force && ! $isDataStale && $plugin->current_image !== null) {
            return $plugin->current_image;
        }

        $usesMarkupPipeline = $output !== PluginOutput::Image;
        $markup = $usesMarkupPipeline ? $plugin->render(device: $device) : '';

        if ($usesMarkupPipeline && $this->shouldSkipFromMarkup($markup)) {
            Log::info('Skipping rendering because markup sets TRMNL_SKIP_DISPLAY', [
                'device_id' => $device->id,
                'plugin_id' => $plugin->id,
            ]);

            $plugin->clearCurrentImage();

            return null;
        }

        $imageUuid = ImageGenerationService::generateImageFromModel(
            markup: $markup,
            deviceModel: $device->deviceModel,
            user: $device->user,
            palette: $device->palette ?? $device->deviceModel?->palette,
            device: $device,
            plugin: $plugin,
            existingImageId: $existingImageId,
        );

        $plugin->update([
            'current_image' => $imageUuid,
            'current_image_metadata' => ImageGenerationService::buildImageMetadataFromDevice($device),
            'data_payload_updated_at' => now(),
        ]);

        ImageGenerationService::cleanupFolder();

        return $imageUuid;
    }

    public function shouldSkipFromPayload(Plugin $plugin): bool
    {
        return is_array($plugin->data_payload)
            && ($plugin->data_payload['TRMNL_SKIP_DISPLAY'] ?? false) === true;
    }

    public function shouldSkipFromMarkup(string $markup): bool
    {
        return preg_match(
            '/<script\b[^>]*>.*?window\.TRMNL_SKIP_DISPLAY\s*=\s*true\b.*?<\/script>/is',
            $markup
        ) === 1;
    }
}
